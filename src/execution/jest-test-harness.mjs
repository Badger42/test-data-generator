import { pathToFileURL } from 'node:url';
import { createTestBatchBuilder } from '../testing/batching/test-batch-builder.mjs';
import { renderJestEachRegistrations } from '../testing/batching/jest-each-generator.mjs';

/** Build the temporary Jest test file for one generated function. */
export function buildJestFeedbackTest(sourceFile, exportName, setupFile, mcdcResultsFile, mcdcRuntimeResultsFile, functionResults, cases, runtimeRecorderSource, batchingOptions = {}) {
  // Keep the full ScenarioCase metadata for the compatibility planner. The
  // generated Jest payload may contain diagnostics/flags needed to force an
  // isolated declaration even when buildJestFeedbackTest is used standalone.
  const testCases = cases.map(item => ({
    ...item,
    testName: item.testName ?? `[Scenario] ${item.id}`,
    mocks: Array.isArray(item.mocks) ? item.mocks : [],
    references: Array.isArray(item.references) ? item.references : [],
  }));
  const selectedExport = exportName ?? (functionResults.length === 1 ? functionResults[0].name : null);
  const batchPlan = batchingOptions.plan ?? (batchingOptions.enabled === false
    ? { batches: [], individual: testCases, stats: { inputCases: testCases.length, batchedCases: 0, individualCases: testCases.length, batchCount: 0, averageBatchSize: 0 } }
    : createTestBatchBuilder({
      minBatchSize: batchingOptions.minBatchSize ?? 2,
      maxBatchSize: batchingOptions.maxBatchSize ?? 100,
    }).build(testCases, {
      functionName: functionResults.length === 1 ? functionResults[0].name : '',
      exportPath: exportName ?? '',
      setupProfileId: setupFile ?? '',
      runtimeKind: 'jest-coverage-feedback',
    }));
  const serializedBatches = JSON.stringify(batchPlan.batches);
  const serializedIndividual = JSON.stringify(batchPlan.individual);
  const testRegistrations = renderJestEachRegistrations(batchPlan);
  const serializedSource = JSON.stringify(pathToFileURL(sourceFile).href);
  const serializedExport = JSON.stringify(selectedExport);
  const serializedSetup = setupFile ? JSON.stringify(pathToFileURL(setupFile).href) : 'null';
  const serializedMcdcResults = JSON.stringify(mcdcResultsFile);
  const serializedMcdcRuntimeResults = JSON.stringify(mcdcRuntimeResultsFile);

  return `/* Generated by branch-scenarios-generator. Do not edit. */
const { beforeAll, beforeEach, afterAll, test, jest } = require('@jest/globals');
const BATCHES = ${serializedBatches};
const INDIVIDUAL_CASES = ${serializedIndividual};
const SOURCE_URL = ${serializedSource};
const EXPORT_PATH = ${serializedExport};
const SETUP_URL = ${serializedSetup};
const MCDC_INPUT_CHECKS_FILE = ${serializedMcdcResults};
const MCDC_RUNTIME_CHECKS_FILE = ${serializedMcdcRuntimeResults};
let targetFunction;

function getByPath(object, expression) {
  if (!expression) return undefined;
  return expression.split('.').reduce((value, key) => value == null ? undefined : value[key], object);
}

function resolveExport(namespace, exportPath) {
  if (typeof namespace === 'function') return namespace;
  if (!exportPath) return undefined;
  let value = getByPath(namespace, exportPath);
  if (value === undefined && namespace.default) value = getByPath(namespace.default, exportPath);
  if (value === undefined && typeof namespace.default === 'function') value = namespace.default;
  return value;
}

function hydrate(value) {
  if (value && typeof value === 'object' && !Array.isArray(value) &&
      Object.keys(value).length === 1 && value.$undefined === true) return undefined;
  if (Array.isArray(value)) return value.map(hydrate);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, hydrate(item)]));
  }
  return value;
}

function readPath(root, expression) {
  return expression.replace(/\\[(\\d+)\\]/g, '.$1').split('.').reduce((value, key) => value == null ? undefined : value[key], root);
}

function buildMcdcScope(scenario, assertion) {
  const args = hydrate(scenario.arguments);
  const scope = {};
  for (const [index, name] of assertion.functionParameterNames.entries()) if (name) scope[name] = args[index];
  const callback = assertion.callbackContext;
  if (callback) {
    const collection = readPath(scope, callback.collection || '');
    const index = callback.iterationIndex ?? 0;
    if (!Array.isArray(collection) || collection[index] === undefined) {
      return { ok: false, reason: 'Callback collection or representative item could not be resolved from the scenario arguments.' };
    }
    const parameters = callback.parameters || [];
    if (parameters[0]) scope[parameters[0]] = collection[index];
    if (parameters[1]) scope[parameters[1]] = index;
  }
  return { ok: true, scope };
}

function evaluateInScope(expression, scope) {
  const names = Object.keys(scope).filter(name => /^[A-Za-z_$][\\w$]*$/.test(name));
  const evaluator = new Function(...names, 'return Boolean(' + expression + ');');
  return evaluator(...names.map(name => scope[name]));
}

function verifyMcdcReference(scenario, reference) {
  const assertion = reference.mcdcAssertion;
  const built = buildMcdcScope(scenario, assertion);
  if (!built.ok) return { status: 'not-evaluable', reason: built.reason };
  try {
    const decisionOutcome = evaluateInScope(assertion.decisionExpression, built.scope);
    if (decisionOutcome !== Boolean(assertion.expectedDecisionOutcome)) {
      return { status: 'mismatch', reason: 'Decision expression did not match the generated expected outcome.', actualDecisionOutcome: decisionOutcome };
    }
    const actualConditions = {};
    for (const condition of assertion.conditions) {
      actualConditions[condition.id] = evaluateInScope(condition.expression, built.scope);
      if (actualConditions[condition.id] !== Boolean(assertion.expectedAtomicConditionValues[condition.id])) {
        return { status: 'mismatch', reason: 'Atomic condition did not match the generated expected value.', actualConditions, mismatchedCondition: condition.id };
      }
    }
    return { status: 'verified', decisionOutcome, actualConditions };
  } catch (error) {
    return { status: 'not-evaluable', reason: error.message };
  }
}

function normalizeCollectionPath(value) {
  // Normalize bracket and dotted numeric path segments to the same path,
  // but preserve numeric segments so sibling collections are not conflated.
  return String(value || '').replace(/\[(\d+)\]/g, '.$1').replace(/\.+/g, '.').replace(/^\.|\.$/g, '');
}

function verifyMcdcAtCallback(assertion, rootScope, callbackArgs) {
  const scope = { ...rootScope };
  const parameters = assertion.callbackContext?.parameters || [];
  for (let index = 0; index < parameters.length; index += 1) {
    if (parameters[index]) scope[parameters[index]] = callbackArgs[index];
  }
  try {
    const decisionOutcome = evaluateInScope(assertion.decisionExpression, scope);
    const actualConditions = {};
    for (const condition of assertion.conditions || []) {
      actualConditions[condition.id] = evaluateInScope(condition.expression, scope);
    }
    const mismatchedCondition = Object.entries(assertion.expectedAtomicConditionValues || {}).find(
      ([conditionId, expected]) => actualConditions[conditionId] !== Boolean(expected),
    )?.[0];
    if (decisionOutcome !== Boolean(assertion.expectedDecisionOutcome) || mismatchedCondition) {
      return {
        status: 'runtime-condition-mismatch',
        decisionOutcome,
        actualConditions,
        ...(mismatchedCondition ? { mismatchedCondition } : {}),
        expectedDecisionOutcome: Boolean(assertion.expectedDecisionOutcome),
      };
    }
    return { status: 'callback-runtime-context-verified', decisionOutcome, actualConditions };
  } catch (error) {
    return { status: 'runtime-not-evaluable', reason: error.message };
  }
}

const TRACKED_CALLBACK_METHODS = new Set([
  'forEach', 'map', 'flatMap', 'some', 'every', 'filter', 'find', 'findIndex',
  'findLast', 'findLastIndex', 'reduce', 'reduceRight', 'sort', 'toSorted',
]);

function createRuntimeTrackedArguments(args, parameterNames, references, runtime) {
  const callbackReferences = references.filter(reference => reference.mcdcAssertion?.callbackContext);
  const proxyCache = new WeakMap();

  function wrapValue(value, valuePath) {
    if (!value || typeof value !== 'object' || value instanceof Date || value instanceof RegExp) return value;
    const prototype = Object.getPrototypeOf(value);
    if (!Array.isArray(value) && prototype !== Object.prototype && prototype !== null) return value;
    let pathCache = proxyCache.get(value);
    if (!pathCache) { pathCache = new Map(); proxyCache.set(value, pathCache); }
    if (pathCache.has(valuePath)) return pathCache.get(valuePath);

    const proxy = new Proxy(value, {
      get(target, property, receiver) {
        const child = Reflect.get(target, property, receiver);
        if (Array.isArray(target) && typeof property === 'string' && TRACKED_CALLBACK_METHODS.has(property) && typeof child === 'function') {
          return function (...methodArgs) {
            const originalCallback = methodArgs[0];
            if (typeof originalCallback === 'function') {
              let callbackInvocation = 0;
              methodArgs[0] = function (...callbackArgs) {
                const callbackIndex = property === 'sort' || property === 'toSorted'
                  ? callbackInvocation++
                  : property === 'reduce' || property === 'reduceRight' ? callbackArgs[2] : callbackArgs[1];
                const previousContext = runtime?.enterCallback?.({
                  method: property,
                  collection: valuePath,
                  iterationIndex: Number.isInteger(callbackIndex) ? callbackIndex : null,
                });
                try { return Reflect.apply(originalCallback, this, callbackArgs); }
                finally { runtime?.leaveCallback?.(previousContext); }
              };
            }
            const output = Reflect.apply(child, receiver, methodArgs);
            return wrapValue(output, valuePath);
          };
        }
        if (typeof property === 'symbol') return child;
        const childPath = Array.isArray(target) && /^\d+$/.test(property)
          ? valuePath + '[' + property + ']'
          : valuePath + '.' + String(property);
        return wrapValue(child, childPath);
      },
      set(target, property, nextValue) { return Reflect.set(target, property, nextValue, target); },
      defineProperty(target, property, descriptor) { return Reflect.defineProperty(target, property, descriptor); },
    });
    pathCache.set(valuePath, proxy);
    return proxy;
  }

  if (!callbackReferences.length) return { args, finalize() {} };
  return { args: args.map((value, index) => wrapValue(value, parameterNames[index] || ('arg' + index))), finalize() {} };
}

${runtimeRecorderSource}

beforeEach(async () => {
  // Every test.each row is an independent Jest test case. Always reset Jest
  // mocks first; an optional project hook may then restore custom spies or
  // adapter state before the row-specific MockPlan is applied.
  jest.resetAllMocks();
  if (typeof globalThis.__BRANCH_SCENARIO_RESET_MOCKS__ === 'function') {
    await globalThis.__BRANCH_SCENARIO_RESET_MOCKS__({ jest });
  }
});

beforeAll(async () => {
  if (SETUP_URL) await import(SETUP_URL);
  const namespace = await import(SOURCE_URL);
  targetFunction = resolveExport(namespace, EXPORT_PATH);
  if (typeof targetFunction !== 'function') {
    throw new Error('Cannot resolve an exported function. Expected export path: ' +
      String(EXPORT_PATH) + '. Export the analyzed function or pass --export <path>.');
  }
});

async function runScenario(scenario) {
    globalThis.__BRANCH_SCENARIO__ = scenario;
    globalThis.__BRANCH_SCENARIO_MOCKS__ = scenario.mocks || [];
    const runtimeRecorder = globalThis[Symbol.for(RUNTIME_MCDC_SYMBOL)];
    runtimeRecorder.beginCase(scenario.id);
    if (typeof globalThis.__BRANCH_SCENARIO_APPLY_MOCKS__ === 'function') {
      await globalThis.__BRANCH_SCENARIO_APPLY_MOCKS__(scenario.mocks || [], scenario);
    }
    for (const reference of scenario.references.filter(item => item.mcdcAssertion)) {
      const verification = verifyMcdcReference(scenario, reference);
      globalThis.__BRANCH_SCENARIO_MCDC_INPUT_CHECKS__.push({
        caseId: scenario.id,
        pairId: reference.pairId,
        decisionId: reference.decisionId,
        conditionId: reference.conditionId,
        side: reference.side,
        ...verification,
      });
      if (verification.status === 'mismatch') {
        throw new Error('MC/DC input-model verification failed for ' + reference.pairId + ' (' + reference.side + '): ' + verification.reason);
      }
    }
    const args = hydrate(scenario.arguments);
    const parameterNames = [...new Set(scenario.references.flatMap(reference => reference.mcdcAssertion?.functionParameterNames || []))];
    const runtimeReferences = scenario.references.filter(reference => reference.mcdcAssertion?.callbackContext)
      .map(reference => ({ ...reference, caseId: scenario.id }));
    const tracked = createRuntimeTrackedArguments(args, parameterNames, runtimeReferences, runtimeRecorder);
    try {
      await targetFunction(...tracked.args);
    } finally {
      tracked.finalize();
    }
}

${testRegistrations}

afterAll(() => {
  require('node:fs').writeFileSync(MCDC_INPUT_CHECKS_FILE, JSON.stringify(globalThis.__BRANCH_SCENARIO_MCDC_INPUT_CHECKS__ || [], null, 2));
  require('node:fs').writeFileSync(MCDC_RUNTIME_CHECKS_FILE, JSON.stringify(globalThis[Symbol.for(RUNTIME_MCDC_SYMBOL)]?.snapshot?.() || [], null, 2));
  delete globalThis.__BRANCH_SCENARIO__;
  delete globalThis.__BRANCH_SCENARIO_MOCKS__;
  delete globalThis.__BRANCH_SCENARIO_RESET_MOCKS__;
  delete globalThis.__BRANCH_SCENARIO_APPLY_MOCKS__;
  delete globalThis.__BRANCH_SCENARIO_MCDC_INPUT_CHECKS__;
  delete globalThis.__BRANCH_SCENARIO_MCDC_RUNTIME_CHECKS__;
  delete globalThis[Symbol.for(RUNTIME_MCDC_SYMBOL)];
});
`;
}

